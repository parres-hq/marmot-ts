#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const phaseDir = join(root, ".planning/phases/05-quality-gate");
const evidence = JSON.parse(
  readFileSync(join(phaseDir, "05-CI-EVIDENCE.json"), "utf8"),
);
const dossierFiles = [
  "05-PROOF-V2-DOSSIER.md",
  "05-KEY-PACKAGE-LIFETIME-DOSSIER.md",
  "05-TAG-CARDINALITY-DOSSIER.md",
  "05-SAFE-AAD-DOSSIER.md",
];

function dossier(file) {
  const markdown = readFileSync(join(phaseDir, file), "utf8");
  const match = markdown.match(
    /<!-- quality-dossier-evidence:start -->\s*```json\s*([\s\S]*?)\s*```/,
  );
  if (!match) throw new Error(`${file}: evidence block missing`);
  return JSON.parse(match[1]);
}

const dossiers = dossierFiles.map(dossier);
const sourceTuples = new Set(
  dossiers.map(({ provenance }) => provenance.tested_source_sha),
);
if (sourceTuples.size !== 1 || !sourceTuples.has(evidence.tested_source_sha))
  throw new Error("CI and dossier evidence do not share one tested source");
if (
  evidence.run.status !== "completed" ||
  evidence.run.conclusion !== "success" ||
  evidence.jobs.length !== 6
)
  throw new Error("hosted matrix is incomplete");
for (const job of evidence.jobs) {
  if (
    job.status !== "completed" ||
    job.conclusion !== "success" ||
    job.normal.tests !== 964 ||
    job.extended.tests !== 1
  )
    throw new Error(`${job.matrix_id}: hosted result is incomplete`);
}

const jobRows = evidence.jobs
  .map(
    (job) =>
      `| ${job.matrix_id} | \`${job.resolved_version}\` | \`${job.pnpm_version}\` | \`${job.vitest_version}\` | [\`${job.job_id}\`](${job.url}) | ${job.normal.test_files}/${job.normal.tests} | ${job.extended.test_files}/${job.extended.tests} | \`${job.log_sha256}\` |`,
  )
  .join("\n");
const dossierRows = dossiers
  .map(
    (record) =>
      `| ${record.dossier} | \`${record.verification.rust_output_or_digest.split("sha256=")[1]}\` | \`${record.verification.typescript_output}\` | \`${record.negative_control.result}\` |`,
  )
  .join("\n");

const gate = `# Phase 5 Quality Gate

<!-- Generated by scripts/render-quality-gate.mjs from 05-CI-EVIDENCE.json and four dossier evidence blocks. Do not edit manually. -->

## Verdict

**PASS** — authenticated hosted evidence and replay-bound dossiers validate tested source \`${evidence.tested_source_sha}\`.

## Immutable provenance

| Field | Value |
| --- | --- |
| Tested source | \`${evidence.tested_source_sha}\` |
| Marmot gitlink | \`${evidence.references.marmot_sha}\` |
| MDK gitlink | \`${evidence.references.mdk_sha}\` |
| ts-mls gitlink | \`${evidence.references.ts_mls_sha}\` |
| Lockfile SHA-256 | \`${dossiers[0].provenance.lockfile_sha256}\` |
| Hosted run | [\`${evidence.run.id}\`](${evidence.run.url}), attempt ${evidence.run.attempt} |

## Hosted runtime authority

Every job completed successfully after \`pnpm install --frozen-lockfile\` and ran the normal and isolated extended suites.

| Row | Runtime | pnpm | Vitest | Immutable job | Normal files/tests | Extended files/tests | Log SHA-256 |
| --- | --- | --- | --- | --- | --- | --- | --- |
${jobRows}

## Cross-implementation dossier authority

The default dossier validator uses a detached worktree on the workspace filesystem, stable absolute Cargo caches, a frozen pnpm 10.18.3 install, compile/build, four locked Rust generators, every assertion in each complete parity file, and separately selected negative controls.

| Dossier | Rust fixture SHA-256 | Full TypeScript result | Negative control result |
| --- | --- | --- | --- |
${dossierRows}

The dossier adversarial suite rejects 104 provenance, command, version, result, and digest mutations. The CI adversarial suite rejects 66 fabricated hosted claims.

## Requirement mapping

| Requirement | Machine evidence | Status |
| --- | --- | --- |
| QA-01 | Authenticated run \`${evidence.run.id}\`, six immutable jobs/log hashes, frozen installs, normal and extended counts | PASS |
| QA-02 | Four replay-bound Rust/TypeScript dossiers at the same source, full parity files, separate negative controls | PASS |

## Reproduce

\`\`\`bash
node scripts/validate-quality-ci.mjs --self-test
node scripts/validate-quality-dossiers.mjs --self-test
node scripts/validate-quality-dossiers.mjs
node scripts/render-quality-gate.mjs
\`\`\`
`;

const summary = `---
phase: 05-quality-gate
plan: 08
subsystem: release
tags: [github-actions, provenance, runtime-matrix, quality-gate]
provides:
  - Authenticated six-runtime normal and extended CI evidence
  - Full parity-file and negative-control dossier replay
  - Machine-generated final quality gate
requirements-completed: [QA-01, QA-02]
status: complete
---

# Phase 5 Plan 8: Hosted Quality Gate Summary

<!-- Generated by scripts/render-quality-gate.mjs from current machine evidence. Do not edit manually. -->

The final tested source is \`${evidence.tested_source_sha}\`. Authenticated Tests run [\`${evidence.run.id}\`](${evidence.run.url}) completed successfully with six immutable runtime jobs. Every row passed 96 files / 964 normal tests and 1 file / 1 extended test using pnpm 10.34.5 and a frozen install.

The four dossiers share that source and reference tuple. Replay uses pnpm 10.18.3, Node ${dossiers[0].environment.node_version}, ${dossiers[0].environment.cargo_version}, ${dossiers[0].environment.rustc_version}, and Vitest ${dossiers[0].verification.vitest_version}. It regenerates each Rust fixture, runs the complete parity files (2, 5, 57, and 4 tests), then executes each mutation control separately.

Machine validation rejects 66 fabricated CI claims and 104 dossier provenance/command/version/result/digest mutations. \`05-QUALITY-GATE.md\` is generated from the same evidence inputs.

## Final evidence

- Tested source: \`${evidence.tested_source_sha}\`
- Hosted run: \`${evidence.run.id}\`, attempt ${evidence.run.attempt}
- Runtime jobs: ${evidence.jobs.map((job) => `\`${job.job_id}\``).join(", ")}
- CI validator: PASS
- Dossier validator: PASS
- QA-01: PASS
- QA-02: PASS

## Reproduction

\`\`\`bash
node scripts/validate-quality-ci.mjs --self-test
node scripts/validate-quality-dossiers.mjs
node scripts/render-quality-gate.mjs
\`\`\`
`;

const outputs = [
  [join(phaseDir, "05-QUALITY-GATE.md"), gate],
  [join(phaseDir, "05-08-SUMMARY.md"), summary],
];
if (process.argv.includes("--check")) {
  for (const [file, expected] of outputs)
    if (readFileSync(file, "utf8") !== expected)
      throw new Error(`${file}: generated evidence is stale; rerun renderer`);
  console.log(
    `PASS: generated Phase 5 gate and summary are current for ${evidence.tested_source_sha}`,
  );
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
  console.log(
    `PASS: rendered Phase 5 gate and summary for ${evidence.tested_source_sha}`,
  );
}
